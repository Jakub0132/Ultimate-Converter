"""Classic Windows-style presentation for the existing conversion workflows."""
import tkinter as tk
from tkinter import ttk

GRAY = '#c0c0c0'
NAVY = '#000080'


def build_ui(app, modes):
    app.configure(bg=GRAY)
    app.geometry('900x650')
    app.minsize(740, 560)
    app.option_add('*Font', ('Tahoma', 10))
    app.option_add('*Background', GRAY)
    app.option_add('*Foreground', 'black')
    app.option_add('*selectBackground', NAVY)
    app.option_add('*selectForeground', 'white')
    style = ttk.Style(app)
    style.theme_use('classic')
    style.configure('.', background=GRAY, foreground='black', font=('Tahoma', 10))
    style.configure('TFrame', background=GRAY)
    style.configure('TLabel', background=GRAY, foreground='black')
    style.configure('Muted.TLabel', foreground='#404040')
    style.configure('TButton', padding=(12, 7), relief='raised', borderwidth=2)
    style.configure('Accent.TButton', font=('Tahoma', 10, 'bold'), padding=(24, 8))
    style.configure('TEntry', fieldbackground='white', padding=5)
    style.configure('TCombobox', fieldbackground='white', padding=5)
    style.map('TCombobox', fieldbackground=[('readonly', 'white')], foreground=[('readonly', 'black')])
    style.configure('Treeview', background='white', fieldbackground='white', foreground='black', rowheight=27, borderwidth=2, relief='sunken')
    style.map('Treeview', background=[('selected', NAVY)], foreground=[('selected', 'white')])
    style.configure('TProgressbar', background=NAVY, troughcolor=GRAY)

    # Keep the OS frame for native resize, minimize, maximize and keyboard support.
    tk.Label(app, text='Ultimate Converter', bg=NAVY, fg='white', font=('Tahoma', 17, 'bold'), anchor='center', padx=10, pady=5).pack(fill='x', padx=4, pady=(4, 0))
    shell = ttk.Frame(app, padding=(14, 6, 14, 8))
    shell.pack(fill='both', expand=True)
    shell.columnconfigure(0, weight=1)
    shell.rowconfigure(1, weight=1)
    tabs = ttk.Frame(shell)
    tabs.grid(row=0, column=0, sticky='w')
    app.tab_buttons = {}
    def select(mode):
        if not app.busy:
            app.mode.set(mode)
            app.change_mode()
    for mode in modes:
        button = tk.Button(tabs, text=mode, relief='raised', borderwidth=2, padx=18, pady=7, command=lambda value=mode: select(value))
        button.pack(side='left', padx=(0, 2))
        app.tab_buttons[mode] = button
    # Compatibility handle used by the existing busy-state code; tabs are guarded.
    app.mode_box = ttk.Combobox(shell, textvariable=app.mode, values=list(modes), state='readonly')
    body = tk.Frame(shell, relief='raised', borderwidth=2)
    body.grid(row=1, column=0, sticky='nsew')
    body.columnconfigure(0, weight=1)
    body.rowconfigure(0, weight=1)
    app.input_group = tk.LabelFrame(body, text='1. Files', padx=12, pady=10, relief='groove', borderwidth=2)
    app.input_group.grid(row=0, column=0, sticky='nsew', padx=12, pady=(12, 8))
    app.input_group.columnconfigure(0, weight=1)
    app.input_group.rowconfigure(0, weight=1)
    app.table_frame = ttk.Frame(app.input_group)
    app.table_frame.grid(row=0, column=0, sticky='nsew')
    app.table = ttk.Treeview(app.table_frame, columns=('name', 'size', 'status'), displaycolumns=('name',), show='', selectmode='extended', height=4)
    app.table.column('name', width=360, minwidth=100)
    scroll = ttk.Scrollbar(app.table_frame, command=app.table.yview)
    app.table.configure(yscrollcommand=scroll.set)
    scroll.pack(side='right', fill='y')
    app.table.pack(fill='both', expand=True)
    app.file_actions = ttk.Frame(app.input_group, padding=(14, 0, 0, 0))
    app.file_actions.grid(row=0, column=1, sticky='ns')
    app.add_button = ttk.Button(app.file_actions, text='Add files…', command=app.add_files, width=19)
    app.add_button.pack(fill='x', pady=(0, 10))
    app.remove_button = ttk.Button(app.file_actions, text='Remove', command=app.remove_files, width=19)
    app.remove_button.pack(fill='x')
    app.youtube_panel = ttk.Frame(app.input_group)
    ttk.Label(app.youtube_panel, text='Video URL:').pack(anchor='w', pady=(0, 6))
    app.url_entry = ttk.Entry(app.youtube_panel, textvariable=app.youtube_url)
    app.url_entry.pack(fill='x')
    ttk.Label(app.youtube_panel, text='Paste a link with Ctrl+V. Shorts are also supported.', style='Muted.TLabel').pack(anchor='w', pady=8)
    app.cancel_button = ttk.Button(app.youtube_panel, text='Cancel download', command=app.request_cancel, state='disabled')
    app.cancel_button.pack(anchor='w')
    output = tk.LabelFrame(body, text='2. Output format', padx=12, pady=10, relief='groove', borderwidth=2)
    output.grid(row=1, column=0, sticky='ew', padx=12, pady=8)
    app.format_box = ttk.Combobox(output, textvariable=app.target, values=modes[app.mode.get()], state='readonly', width=25)
    app.format_box.pack(anchor='w')
    app.note = ttk.Label(output, text='', style='Muted.TLabel', wraplength=650)
    app.note.pack(fill='x', pady=(8, 0))
    output.bind('<Configure>', lambda event: app.note.configure(wraplength=max(200, event.width-30)))
    folder = tk.LabelFrame(body, text='3. Save location', padx=12, pady=12, relief='groove', borderwidth=2)
    folder.grid(row=2, column=0, sticky='ew', padx=12, pady=(8, 12))
    folder.columnconfigure(0, weight=1)
    app.folder_entry = ttk.Entry(folder, textvariable=app.destination)
    app.folder_entry.grid(row=0, column=0, sticky='ew')
    app.folder_button = ttk.Button(folder, text='Browse…', command=app.choose_folder)
    app.folder_button.grid(row=0, column=1, padx=(12, 0))
    actions = ttk.Frame(shell, padding=(0, 10, 0, 8))
    actions.grid(row=2, column=0, sticky='ew')
    ttk.Button(actions, text='Open folder', command=app.open_folder).pack(side='left')
    app.start_button = ttk.Button(actions, text='Convert', style='Accent.TButton', command=app.start, default='active')
    app.start_button.pack(side='right')
    app.progress = ttk.Progressbar(shell, mode='determinate')
    app.progress.grid(row=3, column=0, sticky='ew', pady=(0, 6))
    app.status_label = tk.Label(shell, textvariable=app.status, relief='sunken', borderwidth=2, anchor='w', padx=7, pady=4, wraplength=680)
    app.status_label.grid(row=4, column=0, sticky='ew')
    shell.bind('<Configure>', lambda event: app.status_label.configure(wraplength=max(200, event.width-40)))
